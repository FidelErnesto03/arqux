"""REQ-07: native harness projections (``arqux sync-harnesses``).

Renders the canonical governance kernel from ``.arqux/`` into the files each
agent harness reads natively — ``AGENTS.md``, ``CLAUDE.md``, ``GEMINI.md`` and
``.opencode/instructions.md`` — with a ``source_hash`` header so a single
``arqux drift-check`` detects manual edits and reports the exact diff.

The kernel is deterministic: the packaged ``templates/AGENTS.md`` (the
immutable ArqUX kernel) plus the project identity line. All four projections
therefore embed the same ``source_hash``; drift means the on-disk file no
longer matches what the source would render.
"""
from __future__ import annotations

import difflib
import hashlib
from dataclasses import dataclass
from pathlib import Path

MANAGED_MARKER = "arqux:managed"
_TARGETS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md", ".opencode/instructions.md")


def _template_kernel() -> str:
    kernel = Path(__file__).resolve().parent.parent / "templates" / "AGENTS.md"
    return kernel.read_text(encoding="utf-8")


def render_kernel(project_root: Path) -> str:
    """Canonical governance body projected into every harness file."""
    from ..state import find_project_root

    name = project_root.name
    try:
        root = find_project_root(start=str(project_root))
        if root is not None:
            name = root.parent.name
    except Exception:  # noqa: BLE001
        pass
    return (
        f"<!-- arqux:project {name} — governance lives in .arqux/ "
        f"(brain.cortex, learn-policies.cortex) -->\n\n"
        + _template_kernel()
    )


def source_hash(kernel: str) -> str:
    return hashlib.sha256(kernel.encode("utf-8")).hexdigest()[:16]


def render_projection(kernel: str, target: str) -> str:
    return (
        f"<!-- {MANAGED_MARKER} — generated by `arqux sync-harnesses`; "
        f"manual edits are detected by `arqux drift-check` -->\n"
        f"<!-- source_hash:{source_hash(kernel)} target:{target} -->\n\n"
        f"{kernel}"
    )


@dataclass
class Drift:
    target: str
    status: str  # ok | missing | drift
    diff: str = ""


def drift_report(project_root: Path) -> list[Drift]:
    """Compare each harness file against the projection the source renders."""
    project_root = Path(project_root)
    kernel = render_kernel(project_root)
    report: list[Drift] = []
    for rel in _TARGETS:
        path = project_root / rel
        expected = render_projection(kernel, rel)
        if not path.exists():
            report.append(Drift(rel, "missing"))
            continue
        actual = path.read_text(encoding="utf-8")
        if actual == expected:
            report.append(Drift(rel, "ok"))
            continue
        diff = "\n".join(
            difflib.unified_diff(
                expected.splitlines(), actual.splitlines(),
                fromfile=f"expected/{rel}", tofile=f"actual/{rel}",
                lineterm="",
            )
        )
        report.append(Drift(rel, "drift", diff))
    return report


def sync_harnesses(project_root: Path) -> dict:
    """Write every harness projection; returns targets + source_hash."""
    project_root = Path(project_root)
    kernel = render_kernel(project_root)
    written: list[str] = []
    for rel in _TARGETS:
        path = project_root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_projection(kernel, rel), encoding="utf-8")
        written.append(rel)
    return {"targets": written, "source_hash": source_hash(kernel)}


__all__ = [
    "Drift",
    "MANAGED_MARKER",
    "drift_report",
    "render_kernel",
    "render_projection",
    "source_hash",
    "sync_harnesses",
]
